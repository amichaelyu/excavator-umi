"""ORB-SLAM3 driver: EuRoC export with time-corrected camera stamps, settings YAML, probe run, parsing.

The probe (orbslam_probe.cc) is baked into the umi-excavator-processing image. Inside that image it runs
directly; elsewhere it runs in the image through docker/run.sh (see ``command``).

Settings use ORB-SLAM3's KannalaBrandt8 model with the equidistant fisheye intrinsics and the camera-to-IMU
rotation of configs/camera.json (python -m policy.processing.camera_calibration; translation assumed 0), and
LSM6DSL noise densities.
"""
from __future__ import annotations

import csv
import json
import os
import subprocess
from pathlib import Path

import cv2
import numpy as np
from scipy.spatial.transform import Rotation as Rot

from .fusion import ImuNoise
from .recording import Fisheye, Recording

RUN_SH = Path(__file__).resolve().parents[1] / 'docker' / 'run.sh'
# Where the umi-excavator-processing image (policy/processing/docker/Dockerfile) bakes the probe and vocabulary.
IMAGE_PROBE = '/opt/umi-excavator/bin/orbslam_probe'
IMAGE_VOCABULARY = '/opt/ORB_SLAM3/Vocabulary/ORBvoc.txt'
STATE_NAMES = {-1: 'SYSTEM_NOT_READY', 0: 'NO_IMAGES_YET', 1: 'NOT_INITIALIZED', 2: 'OK',
               3: 'RECENTLY_LOST', 4: 'LOST', 5: 'OK_KLT'}


_EXPORT_LOCKS: dict = {}


def export_euroc(rec: Recording, out: Path, offset_s: float, clahe: bool = False) -> list[int]:
    """Write kept frames (grayscale PNG) and IMU; camera stamps are shifted onto the IMU clock.
    Thread-safe per export directory (imu and camera-only runs share one export)."""
    import threading
    lock = _EXPORT_LOCKS.setdefault(str(out), threading.Lock())
    with lock:
        return _export_euroc(rec, out, offset_s, clahe)


def _export_euroc(rec: Recording, out: Path, offset_s: float, clahe: bool = False) -> list[int]:
    (out / 'mav0' / 'cam0' / 'data').mkdir(parents=True, exist_ok=True)
    (out / 'mav0' / 'imu0').mkdir(parents=True, exist_ok=True)
    idx = np.flatnonzero(rec.keep)
    stamps = [int(round((rec.cam_t[i] + offset_s) * 1e9)) for i in idx]
    cl = cv2.createCLAHE(clipLimit=3.0, tileGridSize=(8, 8)) if clahe else None
    # Remove images from an export made with a different time offset (stale stamps).
    wanted = {f'{ts}.png' for ts in stamps}
    for old in (out / 'mav0' / 'cam0' / 'data').glob('*.png'):
        if old.name not in wanted:
            old.unlink(missing_ok=True)
    for i, ts in zip(idx, stamps):
        p = out / 'mav0' / 'cam0' / 'data' / f'{ts}.png'
        if not p.exists():
            img = rec.image(i)
            cv2.imwrite(str(p), cl.apply(img) if cl is not None else img)
    with open(out / 'mav0' / 'cam0' / 'data.csv', 'w') as f:
        f.write('#timestamp [ns],filename\n')
        for ts in stamps:
            f.write(f'{ts},{ts}.png\n')
    (out / 'camera_timestamps.txt').write_text(''.join(f'{ts}\n' for ts in stamps))
    m = (rec.imu_t > rec.cam_t[idx[0]] + offset_s - 0.5) & (rec.imu_t < rec.cam_t[idx[-1]] + offset_s + 0.5)
    # Only IMU samples after any startup gap preceding the first kept frame.
    t = rec.imu_t[m]
    gaps = np.flatnonzero(np.diff(t) > 0.05)
    first = gaps[-1] + 1 if len(gaps) and t[gaps[-1]] < rec.cam_t[idx[0]] + offset_s else 0
    with open(out / 'mav0' / 'imu0' / 'data.csv', 'w') as f:
        f.write('#timestamp [ns],w_RS_S_x [rad s^-1],w_RS_S_y [rad s^-1],w_RS_S_z [rad s^-1],'
                'a_RS_S_x [m s^-2],a_RS_S_y [m s^-2],a_RS_S_z [m s^-2]\n')
        for k in np.flatnonzero(m)[first:]:
            g = rec.gyro[k]; a = rec.accel[k]
            f.write(f'{int(round(rec.imu_t[k] * 1e9))},{g[0]:.9f},{g[1]:.9f},{g[2]:.9f},{a[0]:.9f},{a[1]:.9f},{a[2]:.9f}\n')
    return stamps


def settings_yaml(cam: Fisheye, R_bc: np.ndarray, t_bc: np.ndarray, noise: ImuNoise, inertial=True,
                  n_features=2000, ini_fast=20, min_fast=7) -> str:
    T = np.eye(4); T[:3, :3] = R_bc; T[:3, 3] = t_bc
    fx, fy, cx, cy = cam.K[0, 0], cam.K[1, 1], cam.K[0, 2], cam.K[1, 2]
    k = cam.D
    lines = ['%YAML:1.0', '# Generated by policy/processing/slam/orbslam.py', 'File.version: "1.0"',
             'Camera.type: "KannalaBrandt8"',
             f'Camera1.fx: {fx:.10f}', f'Camera1.fy: {fy:.10f}', f'Camera1.cx: {cx:.10f}', f'Camera1.cy: {cy:.10f}',
             f'Camera1.k1: {k[0]:.12f}', f'Camera1.k2: {k[1]:.12f}', f'Camera1.k3: {k[2]:.12f}', f'Camera1.k4: {k[3]:.12f}',
             f'Camera.width: {cam.size[0]}', f'Camera.height: {cam.size[1]}', 'Camera.fps: 20', 'Camera.RGB: 0']
    if inertial:
        data = ', '.join(f'{v:.10f}' for v in T.ravel())
        lines += ['# T_b_c1: camera-to-IMU-body transform (rotation estimated from gyro vs. visual rotation;',
                  '# translation not measured, assumed as given).',
                  'IMU.T_b_c1: !!opencv-matrix', '   rows: 4', '   cols: 4', '   dt: f', f'   data: [{data}]',
                  f'IMU.NoiseGyro: {noise.gyro_nd:.3e}  # rad/s/sqrt(Hz); LSM6DSL datasheet 4 mdps/sqrt(Hz), inflated',
                  f'IMU.NoiseAcc: {noise.accel_nd:.3e}  # m/s^2/sqrt(Hz); LSM6DSL datasheet 90 ug/sqrt(Hz) at 4 g, inflated',
                  f'IMU.GyroWalk: {noise.gyro_walk:.3e}  # not in datasheet; conventional value',
                  f'IMU.AccWalk: {noise.accel_walk:.3e}  # not in datasheet; conventional value',
                  'IMU.Frequency: 208.0', 'IMU.InsertKFsWhenLost: 1']
    lines += [f'ORBextractor.nFeatures: {n_features}', 'ORBextractor.scaleFactor: 1.2', 'ORBextractor.nLevels: 8',
              f'ORBextractor.iniThFAST: {ini_fast}', f'ORBextractor.minThFAST: {min_fast}',
              'Viewer.KeyFrameSize: 0.05', 'Viewer.KeyFrameLineWidth: 1.0', 'Viewer.GraphLineWidth: 0.9',
              'Viewer.PointSize: 2.0', 'Viewer.CameraSize: 0.08', 'Viewer.CameraLineWidth: 3.0',
              'Viewer.ViewpointX: 0.0', 'Viewer.ViewpointY: -0.7', 'Viewer.ViewpointZ: -1.8', 'Viewer.ViewpointF: 500.0']
    return '\n'.join(lines) + '\n'


def native_probe() -> tuple[Path, Path] | None:
    """(probe, vocabulary) to run directly, or None to run the probe through Docker.

    The umi-excavator-processing image sets ``ORBSLAM3_PROBE`` (and ``ORBSLAM3_VOCABULARY``) to its baked
    binaries, so code running inside it calls ORB-SLAM3 natively. Elsewhere (the Mac) both are unset.
    """
    probe = os.environ.get('ORBSLAM3_PROBE')
    if not probe:
        return None
    vocabulary = Path(os.environ.get('ORBSLAM3_VOCABULARY') or IMAGE_VOCABULARY)
    for path in (Path(probe), vocabulary):
        if not path.is_file():
            raise FileNotFoundError(f'{path} does not exist (from ORBSLAM3_PROBE / ORBSLAM3_VOCABULARY)')
    return Path(probe), vocabulary


def command(data_dir: Path, export: Path, settings: Path, outdir: Path, mode: str,
            timeout_s=300) -> tuple[list[str], dict | None]:
    """The probe command line and extra environment.

    Natively (inside the image) the paths are passed as they are. Otherwise the probe runs in the
    umi-excavator-processing image via docker/run.sh, which mounts data_dir at /data, so every path must
    live under data_dir.
    """
    limit = ['timeout', '--signal=INT', '--kill-after=10', f'{timeout_s}s']
    native = native_probe()
    if native:
        probe, vocabulary = native
        paths = [Path(p).resolve() for p in (settings, export, export / 'camera_timestamps.txt', outdir)]
        return [*limit, str(probe), str(vocabulary), *map(str, paths), mode], None
    data_dir = data_dir.resolve()
    rel = lambda p: '/data/' + str(Path(p).resolve().relative_to(data_dir))
    cmd = ['bash', str(RUN_SH), 'processing', *limit, IMAGE_PROBE, IMAGE_VOCABULARY, rel(settings), rel(export),
           rel(export / 'camera_timestamps.txt'), rel(outdir), mode]
    return cmd, {'UMI_DATA_DIR': str(data_dir)}


def run(data_dir: Path, export: Path, settings: Path, outdir: Path, mode: str, timeout_s=300) -> int:
    """Run the probe: natively inside the processing image, else in that image through Docker."""
    outdir.mkdir(parents=True, exist_ok=True)
    for f in outdir.glob('map_*.txt'):
        f.unlink()
    cmd, extra = command(data_dir, export, settings, outdir, mode, timeout_s)
    env = dict(os.environ, **extra) if extra else None
    with open(outdir / 'slam.log', 'w') as log:
        return subprocess.run(cmd, stdout=log, stderr=subprocess.STDOUT, env=env).returncode


def parse(outdir: Path, stamps: list[int], R_bc: np.ndarray, t_bc: np.ndarray, inertial: bool):
    """Return per-frame online states and per-map final camera poses.

    maps: {map_id: {'frames': array of frame indices, 'R_wc': (n,3,3), 'p_wc': (n,3), ...}}
    ORB-SLAM3 saves body poses T_wb for inertial runs; they are converted with the same T_b_c.
    """
    rows = list(csv.DictReader(open(outdir / 'tracking.csv'))) if (outdir / 'tracking.csv').exists() else []
    state = np.array([int(r['state']) for r in rows]) if rows else np.zeros(0, int)
    map_id = np.array([int(r['map_id']) for r in rows]) if rows else np.zeros(0, int)
    imu_init = np.array([int(r['imu_initialized']) for r in rows]) if rows else np.zeros(0, int)
    index = {ts: i for i, ts in enumerate(stamps)}
    maps = {}
    info = {}
    if (outdir / 'maps.csv').exists():
        for r in csv.DictReader(open(outdir / 'maps.csv')):
            info[int(r['map_id'])] = {k: int(v) for k, v in r.items()}
    for f in sorted(outdir.glob('map_*.txt')):
        mid = int(f.stem.split('_')[1])
        fr, Rs, ps = [], [], []
        lines = [l for l in f.read_text().split('\n') if len(l.split()) == 8]
        # Frames logged while RECENTLY_LOST repeat the last stamp (ORB-SLAM3 quirk): drop repeats.
        from collections import Counter
        counts = Counter(l.split()[0] for l in lines)
        for line in lines:
            if counts[line.split()[0]] > 1:
                continue
            v = line.split()
            ts = int(round(float(v[0])))
            i = index.get(ts)
            if i is None:  # tolerate float formatting of the stamp
                near = min(stamps, key=lambda s: abs(s - ts))
                if abs(near - ts) > 1000:
                    continue
                i = index[near]
            p = np.array(v[1:4], float); q = np.array(v[4:8], float)  # qx qy qz qw
            R = Rot.from_quat(q).as_matrix()
            if inertial:   # T_wb -> T_wc
                p = p + R @ t_bc; R = R @ R_bc
            fr.append(i); Rs.append(R); ps.append(p)
        if not fr and lines:
            raise RuntimeError(f'{f}: no saved pose matches the current camera stamps (stale ORB-SLAM3 cache?)')
        if fr:
            o = np.argsort(fr)
            maps[mid] = {'frames': np.array(fr)[o], 'R_wc': np.array(Rs)[o], 'p_wc': np.array(ps)[o],
                         **info.get(mid, {})}
    return {'state': state, 'map_id': map_id, 'imu_initialized': imu_init, 'maps': maps, 'map_info': info}


VARIANTS = {
    'default': dict(clahe=False, n_features=2000, ini_fast=20, min_fast=7),
    'clahe': dict(clahe=True, n_features=2500, ini_fast=12, min_fast=5),
}


def run_episode(rec: Recording, cam: Fisheye, data_dir: Path, R_bc, t_bc, offset_s, noise: ImuNoise,
                variant='default', mode='imu', rerun=False):
    v = VARIANTS[variant]
    export = data_dir / 'exports' / ('clahe' if v['clahe'] else 'raw') / rec.id
    stamps = export_euroc(rec, export, offset_s, clahe=v['clahe'])
    settings = data_dir / 'settings' / rec.id / f'{variant}-{mode}.yaml'
    settings.parent.mkdir(parents=True, exist_ok=True)
    old_settings = settings.read_text() if settings.exists() else None
    settings.write_text(settings_yaml(cam, R_bc, t_bc, noise, inertial=mode == 'imu', n_features=v['n_features'],
                                      ini_fast=v['ini_fast'], min_fast=v['min_fast']))
    out = data_dir / 'results' / f'{variant}-{mode}' / rec.id
    # Cached results are only valid for the exact settings and camera stamps (time offset) they were run with.
    import hashlib
    key = hashlib.sha256((settings.read_text() + '\n'.join(map(str, stamps))).encode()).hexdigest()
    prov = out / 'provenance.json'
    cached = (out / 'maps.csv').exists() and prov.exists() and json.loads(prov.read_text()).get('key') == key
    if (out / 'maps.csv').exists() and not prov.exists() and old_settings == settings.read_text():
        # Legacy cache without provenance: valid only if it was run on exactly these camera stamps.
        rows = list(csv.DictReader(open(out / 'tracking.csv')))
        if [int(r['timestamp_ns']) for r in rows] == list(stamps):
            cached = True
            prov.write_text(json.dumps({'key': key, 'offset_s': offset_s, 'R_bc': np.asarray(R_bc).tolist(),
                                        'variant': variant, 'mode': mode, 'legacy_verified': True}, indent=1))
    rc = 0
    if rerun or not cached:
        rc = run(data_dir, export, settings, out, mode)
        prov.write_text(json.dumps({'key': key, 'offset_s': offset_s, 'R_bc': np.asarray(R_bc).tolist(),
                                    'variant': variant, 'mode': mode}, indent=1))
    res = parse(out, stamps, R_bc, t_bc, mode == 'imu')
    res.update(returncode=rc, variant=variant, mode=mode, outdir=str(out), settings=settings.read_text())
    return res


def summarize(res, n_frames):
    s = res['state']
    ok = s == 2
    segs = []
    cur = None
    for i in range(len(s)):
        if ok[i]:
            if cur is None or res['map_id'][i] != cur['map_id']:
                cur = {'first': i, 'last': i, 'map_id': int(res['map_id'][i])}
                segs.append(cur)
            cur['last'] = i
        else:
            cur = None
    in_maps = sum(len(m['frames']) for m in res['maps'].values())
    return {'variant': res['variant'], 'mode': res['mode'], 'returncode': res['returncode'],
            'frames': n_frames, 'online_ok': int(ok.sum()), 'online_recently_lost': int((s == 3).sum()),
            'online_segments': len(segs), 'frames_in_saved_maps': int(in_maps),
            'maps': {int(k): {kk: (int(vv) if not isinstance(vv, np.ndarray) else None) for kk, vv in m.items()
                              if kk not in ('frames', 'R_wc', 'p_wc')} | {'n': int(len(m['frames']))}
                     for k, m in res['maps'].items()},
            'imu_initialized_frames': int(res['imu_initialized'].sum()) if len(res['imu_initialized']) else 0}
