"""Write <out>/summary.md from the per-episode summary.json files and calibration.json."""
from __future__ import annotations

import json

import numpy as np

from . import pipeline, recording
from .recording import episode_ids

MARKER = '<!-- hand-written assessment below is preserved on regeneration -->'


def write_summary():
    ARTIFACTS = pipeline.ARTIFACTS
    cal = pipeline.load_calibration()[0]
    name = recording.DATASET.name
    title = 'Soil-digging' if name == 'soil-digging' else name.replace('-', ' ').capitalize()
    src = ARTIFACTS / 'calibration_source.txt'
    reused = [f'Calibration reused, not re-estimated: {src.read_text().strip()}', ''] if src.exists() else []
    rows = []
    failed = []
    for e in episode_ids():
        f = ARTIFACTS / e / 'summary.json'
        if f.exists():
            d = json.loads(f.read_text())
            (failed if d.get('failed') else rows).append(d)
    p = cal['pooled']
    if cal['per_episode']:                   # a per-dataset natural-feature fit (camera_calibration --natural)
        calibration = [
         f'## Camera/IMU calibration (pooled over all {len(cal["per_episode"])} episodes)', '',
         f"- Time offset (matching IMU time = raw camera time + offset): **{p['offset_s']*1e3:.2f} ms** pooled "
         f"(formal 1-sigma {p['offset_sd_s']*1e3:.2f} ms). Per-episode fits: "
         + ', '.join(f"{v['offset_ms']:.1f}" for v in cal['per_episode'].values()) + ' ms. '
         f"Leave-one-out range: {min(x['offset_ms'] for x in cal['leave_one_out']):.2f} to "
         f"{max(x['offset_ms'] for x in cal['leave_one_out']):.2f} ms. The old stored +20.23 ms is not used.",
         f"- Rotation R_imu_camera (rows: IMU axes in camera frame^T): `{np.round(np.array(p['R_imu_cam']), 4).tolist()}`; "
         f"formal sd {', '.join(f'{x:.2f}' for x in p['rotation_sd_deg'])} deg; leave-one-out changes up to "
         f"{max(x['rotation_change_deg'] for x in cal['leave_one_out']):.2f} deg.",
         f"- Gyro vs. visual rotation-rate agreement: median residual {p['residual_median_dps']:.2f} dps, inlier RMS "
         f"{p['residual_rms_inliers_dps']:.2f} dps over {p['pairs']} frame pairs (motion RMS {p['motion_rms_dps']:.1f} dps); "
         f"speed correlation {p['speed_correlation']:.3f}."]
    else:                                    # configs/camera.json camera_imu
        m = cal['camera_imu']
        calibration = [
         f"## Camera/IMU calibration (configs/camera.json, recording {m.get('recording_id') or m.get('source', '?')})", '',
         f"- Time offset (matching IMU time = raw camera time + offset): **{p['offset_s']*1e3:.2f} ms**; {m.get('method', '')}.",
         f"- Rotation R_imu_camera (rows: IMU axes in camera frame^T): `{np.round(np.array(p['R_imu_cam']), 4).tolist()}`.",
         f"- Gyro bias prior of every episode: {np.round(m['gyro_bias_dps'], 2).tolist()} dps; check "
         f"{json.dumps(m.get('check', {}), default=float)}."]
    L = [f'# {title} ORB-SLAM3 + IMU smoother trajectories', '',
         'Generated by `python -m policy.processing.slam all`.', '',
         *reused, *calibration,
         '- Camera-to-IMU translation: not observable from rotation rates, not measured; **assumed 0** '
         '(rigid mount on one bucket, likely < 5 cm).', '',
         '## Per-episode results', '',
         '| Episode | Label | Data quality | Frames | SLAM segs | Gate | Visually tracked | IMU-only (longest gap) | ORB-SLAM3 VI: online OK / in final map | '
         'ORB-SLAM3 camera-only: in maps | Path [m] | Extent x/y/z [m] | Max speed [m/s] | '
         'Scale sensitivity | Gravity resid. [deg] | Scale conf. |',
         '|---|---|---|---:|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|']
    for s in rows:
        vi = s['slam_front_end'].get('orb_slam3_vi') or {}
        mono = s['slam_front_end'].get('orb_slam3_camera_only') or {}
        mono_best = max((v['frames_in_saved_maps'] for v in mono.values()), default=0)
        n = s['frames_processed']
        g = s['gravity_alignment_residual_deg']['all_frames_median']
        sp = s['scale']['sensitivity_max_abs_log_path_ratio']
        gt = s.get('plausibility_gate', {})
        gate = ('fired, ' + gt.get('selected_init', '?') if gt.get('fired') else 'ok') if gt.get('passed', True) else 'FAILED'
        dq = ', '.join(s.get('data_quality', {}).get('flags', [])) or 'ok'
        L.append(f"| `{s['episode']}` | {s.get('label') or '-'} | {dq} | {n} | {s.get('n_slam_segments_in_fusion', '?')} | {gate} | {s['frames_tracked']} ({100*s['frames_tracked']/n:.0f}%) | "
                 f"{s['frames_imu_only']} ({s['longest_imu_only_gap_s']:.2f} s) | "
                 f"{vi.get('online_ok', 0)} / {vi.get('frames_in_saved_maps', 0)} | {mono_best} | "
                 f"{s['path_length_m']:.2f} | {'/'.join(f'{x:.2f}' for x in s['extent_m'])} | "
                 f"{s['max_speed_mps']:.2f} | {'n/a' if sp is None else f'{100*(np.exp(sp)-1):.0f}%'} | "
                 f"{'n/a' if g is None else f'{g:.2f}'} | {s['scale']['confidence']} |")
    for s in failed:
        L.append(f"| `{s['episode']}` | {s.get('label') or '-'} | FAILED: {s.get('error')} |" + ' |' * 14)
    L += ['', 'Columns: *Data quality* = flags from the dataset manifest (needs_review, video_recovered, '
          'recorder_error/warning) and from the loader (IMU ended early and was truncated, undecodable or leniently '
          'decoded JPEG frames, truncated CSVs, invalid IMU samples removed); full detail in `summary.json` '
          '`data_quality`. *Label* = `label` column of `episodes.csv` (blank = unlabeled soil scoop); '
          '*SLAM segs* = ORB-SLAM3 map segments (scale-consistent) used in the fusion; *Gate* = plausibility gate '
          '(max speed 0.5 m/s, extent 0.5 m, IMU whitened RMS 1.5): ok = first solve plausible, fired = a restart '
          'was needed (selected initialisation shown), FAILED = no plausible solution (written, confidence low); '
          '*Visually tracked* = frames with at least one visual factor (ORB-SLAM3 map pose or KLT '
          'two-view pair); *IMU-only* = frames bridged purely by IMU propagation inside the smoother; '
          '*Scale sensitivity* = largest path-length change when the accelerometer noise is halved/doubled, the '
          'gyro noise tripled or the accel-bias prior widened; *Gravity resid.* = median angle over all frames between the '
          'measured specific force (bias-corrected, 100 ms mean) and the smoother-predicted R^T(a - g).', '']
    L += ['## SLAM segment scales', '',
          '| Episode | Source | Map | Frames | t [s] | Map extent [map units] | Fused scale (m per map unit) |', '|---|---|---:|---:|---|---:|---:|']
    for s in rows:
        for sg in s['orb_slam3_segments_in_fusion']:
            L.append(f"| `{s['episode'][-8:]}` | {sg['source']} | {sg['map_id']} | {sg['frames']} | "
                     f"{sg['t_first_s']:.2f}-{sg['t_last_s']:.2f} | {sg['extent_map_units']:.3f} | {sg['fused_scale_factor']:.3f} |")
    L.append('')
    old = (ARTIFACTS / 'summary.md').read_text() if (ARTIFACTS / 'summary.md').exists() else ''
    L.append(MARKER)
    if MARKER in old:
        L.append(old.split(MARKER, 1)[1].strip('\n'))
    (ARTIFACTS / 'summary.md').write_text('\n'.join(L) + '\n')
    print(f'wrote {ARTIFACTS / "summary.md"}')
